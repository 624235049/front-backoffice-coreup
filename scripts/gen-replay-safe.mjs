// Emits src/lib/api-client/replay-safe.gen.ts: every `METHOD /v1/path/{template}` whose OpenAPI operation carries
// `x-replay-safe: true` (the API deduplicates it by Idempotency-Key, so a retry cannot repeat the change).
// Same source as `gen:api`: API_OPENAPI_URL (file path or http(s) URL), default ./openapi.json.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = process.env.API_OPENAPI_URL ?? path.join(root, 'openapi.json');
const text = /^https?:\/\//.test(source)
  ? await (await fetch(source)).text()
  : await readFile(source, 'utf8');
const doc = JSON.parse(text);

const MUTATING = ['post', 'put', 'patch', 'delete'];
const operations = [];
for (const [route, item] of Object.entries(doc.paths ?? {})) {
  for (const method of MUTATING) {
    if (item[method]?.['x-replay-safe'] === true) operations.push(`${method.toUpperCase()} ${route}`);
  }
}
operations.sort();

const out = `// Generated by scripts/gen-replay-safe.mjs from the API OpenAPI document (\`pnpm gen:api\`). Do not edit.
/** Operations the API deduplicates by \`Idempotency-Key\` (OpenAPI \`x-replay-safe\`): safe to replay after a transport failure. */
export const REPLAY_SAFE_OPERATIONS: readonly string[] = [
${operations.map((o) => `  '${o}',`).join('\n')}
];
`;
await writeFile(path.join(root, 'src/lib/api-client/replay-safe.gen.ts'), out);
console.log(`replay-safe.gen.ts: ${operations.length} operations`);
